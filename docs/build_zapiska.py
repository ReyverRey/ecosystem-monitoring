def add_seq_caption(par, kind, number):
    """Абзац с полем SEQ: «Таблица N – ...» уже начинается текстом."""
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), f"SEQ {kind} \\* ARABIC")
    run = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = str(number)
    run.append(t)
    fld.append(run)
    par._p.append(fld)


def table_caption(title):
    global tab_n
