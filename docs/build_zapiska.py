def p(text, indent=True, bold=False, align=None, size=None):
    par = doc.add_paragraph()
    if not indent:
        par.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        par.alignment = align
    run = par.add_run(text)
    run.bold = bold
    if size:
        run.font.size = Pt(size)
    return par


