    cap.paragraph_format.space_after = Pt(8)
    cap.paragraph_format.line_spacing = 1.0
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = cap.add_run("Рисунок ")
    run.font.size = Pt(10)
    add_seq_caption(cap, "Рисунок", fig_n)
    run = cap.add_run(f" – {title}")
    run.font.size = Pt(10)


